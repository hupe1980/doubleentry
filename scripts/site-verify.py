#!/usr/bin/env python3
"""Compile — and, unless marked `no_run`, run — every Rust block on the site.

The README is included into the crate with `#[doc = include_str!]`, so rustdoc
compiles and runs each of its examples. The site cannot use that trick: rustdoc
hides `# ` lines, and Zola would print them. So the site's snippets stay clean
and are verified here instead (ported from the sibling `billing` crate).

Every fenced ```rust block under `site/content/` becomes one test in a
generated, git-ignored `tests/site_examples.rs`, wrapped in a function that
returns `Result<(), Box<dyn std::error::Error>>` so `?` works as in a doctest:

- a block containing `.await` becomes an `async fn` driven by `#[tokio::test]`;
- ```rust,no_run is compiled but never called (PostgreSQL, network);
- ```rust,ignore is refused: every block on the site must at least compile.

    just site-verify                      # every page
    python3 -I scripts/site-verify.py site/content/docs/start   # some pages

The test file is formatted with rustfmt (so `cargo fmt --check` never trips on
it), compiled with `--all-features --locked`, and deleted again on success.
"""

import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "site" / "content"
NAME = os.environ.get("SITE_VERIFY_NAME", "site_examples")
OUT = ROOT / "tests" / f"{NAME}.rs"

FENCE = re.compile(r"^```rust([^\n]*)\n(.*?)^```", re.S | re.M)


def pages(args):
    if not args:
        return sorted(CONTENT.rglob("*.md"))
    found = []
    for arg in args:
        path = (ROOT / arg) if not pathlib.Path(arg).is_absolute() else pathlib.Path(arg)
        found += sorted(path.rglob("*.md")) if path.is_dir() else [path]
    return found


def indent(code):
    return [f"        {line}" if line.strip() else "" for line in code.rstrip().split("\n")]


header = [
    "//! GENERATED by `just site-verify` — do not edit, and do not commit.",
    "//!",
    "//! One test per fenced Rust block on the documentation site; see",
    "//! `scripts/site-verify.py` for why the site cannot use the README's",
    "//! `include_str!` doctest hook.",
    "#![allow(unused_imports, unused_variables, unused_mut, dead_code, clippy::all)]",
    "",
]
body, run, compiled, refused = [], 0, 0, []

for md in pages(sys.argv[1:]):
    rel = md.relative_to(CONTENT).as_posix()
    stem = re.sub(r"[^a-z0-9]+", "_", md.relative_to(CONTENT).with_suffix("").as_posix().lower()).strip("_")
    text = md.read_text(encoding="utf-8")
    for i, m in enumerate(FENCE.finditer(text)):
        info, code = m.group(1), m.group(2)
        line = text.count("\n", 0, m.start()) + 1
        flags = {f.strip() for f in info.split(",") if f.strip()}
        if "ignore" in flags:
            refused.append(f"site/content/{rel}:{line}")
            continue
        is_async = ".await" in code
        no_run = "no_run" in flags
        name = f"{stem}_{i}"
        sig = "async fn example()" if is_async else "fn example()"
        inner = [
            f"    {sig} -> Result<(), Box<dyn std::error::Error>> {{",
            *indent(code),
            "        #[allow(unreachable_code)]",
            "        Ok(())",
            "    }",
        ]
        body.append(f"/// From `site/content/{rel}` line {line}.")
        if no_run:
            compiled += 1
            # Compiled, never called: a module keeps the inner `example`
            # names apart.
            body += [f"mod {name} {{", "    #[allow(dead_code)]", *inner, "}", ""]
            continue
        run += 1
        call = "example().await" if is_async else "example()"
        attr = "#[tokio::test]" if is_async else "#[test]"
        prefix = "async fn" if is_async else "fn"
        body += [
            attr,
            f"{prefix} {name}() {{",
            *inner,
            f"    if let Err(error) = {call} {{",
            f'        panic!("site example site/content/{rel}:{line} failed: {{error}}");',
            "    }",
            "}",
            "",
        ]

if refused:
    print("❌ `rust,ignore` is not allowed on the site — every block must compile:", file=sys.stderr)
    for where in refused:
        print(f"  {where}", file=sys.stderr)
    sys.exit(1)

OUT.write_text("\n".join(header + body) + "\n", encoding="utf-8")
subprocess.call(["rustfmt", "--edition", "2024", str(OUT)])
print(f"generated {run + compiled} tests from the site ({run} run, {compiled} no_run, 0 marked ignore) -> {OUT.relative_to(ROOT)}")

rc = subprocess.call(
    ["cargo", "test", "--locked", "--all-features", "--test", NAME], cwd=ROOT
)

# Remove it again: left in tests/, it would be one more test binary every
# `cargo test` and every mutation run rebuilds, for a target that checks
# documentation rather than behaviour.
if rc == 0:
    OUT.unlink(missing_ok=True)
else:
    print(f"\nleft {OUT.relative_to(ROOT)} in place so the failure can be inspected", file=sys.stderr)
sys.exit(rc)
